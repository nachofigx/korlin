#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Genera el protocolo C-24 en markdown desde el diseno real."""
import json
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
d = json.loads((RAIZ / "docs" / "c24-estimulos.json").read_text(encoding="utf-8"))
a = d["bloques"]["A_colisiones"]
b = d["bloques"]["B_cluster_hV"]
c = d["bloques"]["C_naturalidad"]

L = []
w = L.append
w("# Protocolo C-24 — Medición con hablantes")
w("")
w("**Fecha:** 24-oct-2026 · **Autor:** linguista · **Estado:** listo para aplicar")
w("")
w("**Objetivo:** medir tres cosas que no se pueden decidir desde el escritorio:")
w("si las colisiones canónicas estorban (las cinco prosódicas y el homófono")
w("`kilo` ≈ `ki-lo`), si el racimo `hV-` cuesta reconocer,")
w("y si el léxico suena natural. **El resultado decide si se renombran formas.**")
w("`kilo`, `mega` y `nano` no se renombran: si A6 falla, se refuerza la escritura")
w("(guion en `ki-lo`, contexto numérico en `kilo`), no el nombre.")
w("")
w("---")
w("")
w("## 0. Qué NO hace falta y qué sí")
w("")
w("| Bloque | Mide | Cómo | Coste por hablante |")
w("|---|---|---|---|")
w(f"| A — colisiones | discriminación de {a['n_items']} pares | **escrito**, elección forzada | 4 min |")
w(f"| B — racimo hV- | identificación de {b['n_items']} vecinos | **escrito**, elección múltiple | 5 min |")
w(f"| C — naturalidad | juicio del léxico ({c['n_items']} formas) | **escrito**, escala 1-5 | 6 min |")
w("")
w("**Total por hablante: ~15 minutos.** Se puede hacer en una sesión o en dos.")
w("")
w("### Por qué todo es escrito (decisión basada en una medición)")
w("")
w("La versión con audio **no es viable**, y no por falta de medios. Medido con")
w("`scripts/c24_audio.py`:")
w("")
w("- **La /h/ es muda en la voz `es-MX`.** El audio de `halo` y de `alo` es idéntico")
w("  (misma duración de voz, mismo RMS): la `h` no se pronuncia. Verificado que en")
w("  `en-US`, `de-DE`, `pt-BR` e `it-IT` sí se pronuncia, pero esas voces no respetan")
w("  la fonología de Korlin.")
w("- **El TTS no marca la diferencia de acento.** `halo` y `ha lo` salen con el mismo")
w("  patrón: una sola pausa interna de ~0.11 s en ambos casos. El sintetizador trata")
w("  la secuencia como un único grupo prosódico, que es justo lo que hay que medir.")
w("")
w("**Consecuencia:** la oposición 1 acento vs 2 acentos no se puede grabar con este")
w("instrumento. Se mide **en la escritura con guion**, que es exactamente donde la")
w("lengua la resuelve. Si más adelante hace falta medirla en habla, hace falta una")
w("grabación humana: no se puede sustituir con TTS.")
w("")
w("---")
w("")
w("## 1. Cómo reclutar (sin engañar al hablante)")
w("")
w("**Perfil buscado:** hispanohablante nativo, sin formación en lingüística.")
w("**N mínimo: 8.** Ideal 12. Con menos de 8 los porcentajes no dicen nada.")
w("")
w("El hablante **no debe saber** qué se está probando. Si se le dice «vas a ver si")
w("`kilo` se confunde con `ki lo`», responderá con cuidado y la medida se pierde.")
w("")
w("Instrucción verbal, literal:")
w("")
w("> «Te voy a mostrar palabras de un idioma inventado. Léelas como las dirías tú.")
w("> No hay respuestas correctas: me interesa tu impresión.»")
w("")
w("**No** se enseña el manual primero. **No** se da el léxico. Se mide la primera")
w("impresión, que es la que tendrá quien se acerque a la lengua por primera vez.")
w("")
w("---")
w("")
w("## 2. Bloque A — colisiones canónicas")
w("")
w("### Tarea")
w("")
w("Se muestra **una de las dos formas** (sorteada) en una frase, y el hablante elige")
w("qué quiso decir entre dos paráfrasis en español. **Sin contexto previo.**")
w("")
w("### Material")
w("")
w("| # | Forma | Lectura alterna | Oración (la forma va con guion) | Opción 1 | Opción 2 |")
w("|---|---|---|---|---|---|")
for it in sorted(a["items"], key=lambda x: x["par"]):
    if it["id"].endswith("-2"):
        continue
    w(f"| {it['par']} | `{it['estimulo_A']}` | `{it['estimulo_B']}` | {it['oracion_A']} "
      f"| {it['glosa_A']} | {it['glosa_B']} |")
w("")
w("### Las dos condiciones")
w("")
w("Cada par se prueba **dos veces**:")
w("")
w("1. **Sin guion** (la forma a secas). Registra la primera lectura.")
w("2. **Con guion** en su lugar (`ha-lo` vs `ha lo`). Registra si el guion desambigua.")
w("")
w("La comparación entre las dos condiciones es el dato: si con guion sube el acierto,")
w("el guion funciona y **no hay que renombrar nada**.")
w("")
w("### Par A6 — homófono verdadero `kilo` ≈ `ki-lo`")
w("")
w("A1–A5 oponen un acento a dos (`kilo` ≈ `ki lo`, con espacio). A6 es la sexta")
w("colisión (deuda C-05, regla 21): `kilo` (×10³) y `ki-lo` (*dónde*) son los dos")
w("una palabra y el mismo /ˈki.lo/. El guion no cambia el acento; es la mitigación")
w("escrita, junto con el contexto numérico de `kilo` y la prohibición de")
w("coocurrir en la misma cláusula. A6-1 presenta `kilo`; A6-2 presenta `ki-lo`.")
w("Los ítems A1–A5, B y C conservan el orden de la semilla `20261024`; A6 se")
w("añade al final del bloque A y no los reordena.")
w("")
w("### Pregunta de cierre (la más importante)")
w("")
w("Al terminar el bloque, se pregunta **sin mostrar el material**:")
w("")
w("> «¿Notaste alguna vez que una palabra pudiera leerse de dos maneras?»")
w("")
w("Un hablante que **no lo notó** es el mejor resultado posible: significa que la")
w("colisión no llega a la conciencia. Se anota tal cual, y si espontáneamente nombra")
w("alguna, se anota cuál.")
w("")
w("---")
w("")
w("## 3. Bloque B — racimo `hV-`")
w("")
w("14 formas que empiezan por `h` + vocal. Se oye/lee una y se elige entre 4 escritas.")
w("")
w("**El riesgo que se mide:** que los vecinos se confundan entre sí. Si `hodu`")
w("(*montaña*) y `hoki` (*dinero*) se cruzan sistemáticamente, el racimo es un problema")
w("real y hay que espaciarlo (es lo que Korlin dejó anotado como deuda).")
w("")
w("| # | Forma | Español | Distractores (vecinos mínimos) |")
w("|---|---|---|---|")
for it in sorted(b["items"], key=lambda x: x["id"]):
    dist = [o for o in it["opciones"] if o != it["respuesta_correcta"]]
    w(f"| {it['id']} | `{it['estimulo']}` | {it['glosa']} | {' · '.join(f'`{x}`' for x in dist)} |")
w("")
w("### Qué se mide")
w("")
w("No el acierto bruto (siempre hay azar: 25% por 4 opciones), sino **la tasa de")
w("confusión por par concreto**. Se anota qué forma se eligió cuando se falló: si los")
w("errores se concentran en un vecino determinado (`hoki`→`huki` una y otra vez), ese")
w("par es el problema, no el racimo entero.")
w("")
w("---")
w("")
w("## 4. Bloque C — naturalidad del léxico")
w("")
w("30 formas al azar (estratificadas por categoría). El hablante puntúa 1-5:")
w("")
w("> «¿Qué tan natural te suena como palabra de un idioma? 1 = raro, parece un error;")
w("> 5 = normal, como una palabra que ya conocieras.»")
w("")
w("### Qué se mide")
w("")
w("**La cola, no el promedio.** El promedio siempre sale 3 y no dice nada. Lo que")
w("importa son las formas con puntuación ≤ 2 de forma consistente entre hablantes:")
w("esas son las candidatas a renombrar. Una forma que a 8 personas les parece rara")
w("tiene un problema real, aunque a la gramática no le pase nada.")
w("")
w("---")
w("")
w("## 5. Umbrales de decisión (fijados ANTES de medir)")
w("")
w("Se fijan ahora para no racionalizar el resultado después:")
w("")
w("| Resultado | Lectura | Acción |")
w("|---|---|---|")
w("| **≥ 90%** de acierto en A y B | sin problema | no se toca nada |")
w("| **75-90%** | vigilancia | se anota; se revisa si se suma otro indicio |")
w("| **< 75%** en un par concreto | fallo real | **se renombra ese par** (uno a uno, no la lista) |")
w("| Bloque C: forma con ≤ 2 en ≥ 60% de hablantes | suena mal | candidata a renombrar |")
w("")
w("**Mínimo para renombrar: 3 hablantes coincidiendo en el mismo par.** Uno solo no")
w("justifica tocar el léxico: puede ser idiosincrasia.")
w("")
w("---")
w("")
w("## 6. Registro")
w("")
w("- Plantilla: `docs/c24-plantilla.csv` (una fila por hablante en la cabecera).")
w("- Hoja legible: `docs/c24-hoja-respuestas.md` — una por hablante.")
w("- Diseño completo con el orden ya sorteado: `docs/c24-estimulos.json`.")
w("")
w("**El orden está fijado con semilla** (`20261024`): varias sesiones usan el mismo")
w("orden y los resultados son comparables. Si se cambia la semilla, hay que anotarlo.")
w("La semilla no cambió al añadir A6: ese par no rebaraja A1–A5, B ni C.")
w("")
w("Una vez vaciados los datos, el análisis se hace con `scripts/c24_analiza.py`.")
w("")
w("---")
w("")
w("## 7. Lo que esta prueba NO puede decidir")
w("")
w("- **No valida la pronunciación real de la /h/** en habla: eso necesita grabación")
w("  humana. Lo que mide es el reconocimiento escrito.")
w("- **No mide si la lengua es fácil de aprender**: eso es un estudio longitudinal.")
w("- **No decide el nombre `Korlin`**: es marca, y es de Ignacio.")
w("- Con 8-12 hablantes hispanohablantes mide **hispanohablantes**, no «la humanidad».")
w("  Si algún día hay hablantes de otras lenguas maternas, es otra prueba.")

(RAIZ / "docs" / "c24-protocolo.md").write_text("\n".join(L), encoding="utf-8")
print(f"escrito docs/c24-protocolo.md ({len(L)} lineas)")
